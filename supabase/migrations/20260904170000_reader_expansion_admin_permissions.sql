create or replace function public.sync_reader_rank()
returns text language plpgsql security definer set search_path = public as $$
declare thresholds jsonb; next_rank text := 'visitor'; earned_xp integer := 0;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  select coalesce(sum(xp), 0) into earned_xp from public.user_achievements where user_id = auth.uid();
  select rank_thresholds into thresholds from public.platform_settings where singleton = true;
  if earned_xp >= coalesce((thresholds->>'explorer')::integer, 100) then next_rank := 'explorer'; end if;
  if earned_xp >= coalesce((thresholds->>'debater')::integer, 500) then next_rank := 'debater'; end if;
  if earned_xp >= coalesce((thresholds->>'connector')::integer, 1500) then next_rank := 'connector'; end if;
  if earned_xp >= coalesce((thresholds->>'curator')::integer, 5000) then next_rank := 'curator'; end if;
  if earned_xp >= coalesce((thresholds->>'legend')::integer, 10000) then next_rank := 'legend'; end if;
  perform set_config('app.allow_role_change', 'true', true);
  update public.profiles set reader_rank = next_rank where id = auth.uid() and rank_manual = false;
  return (select reader_rank from public.profiles where id = auth.uid());
end;
$$;
revoke all on function public.sync_reader_rank() from public, anon;
grant execute on function public.sync_reader_rank() to authenticated;

create or replace function public.owner_update_platform_settings(
  displayed_days integer,
  max_protections integer,
  renewal_period text,
  new_rank_thresholds jsonb
)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_app_owner() then raise exception 'Owner access required'; end if;
  if displayed_days not between 7 and 366 or max_protections not between 0 and 31 or renewal_period <> 'monthly' then
    raise exception 'Invalid platform settings';
  end if;
  if (new_rank_thresholds->>'explorer')::integer < 0
    or (new_rank_thresholds->>'debater')::integer <= (new_rank_thresholds->>'explorer')::integer
    or (new_rank_thresholds->>'connector')::integer <= (new_rank_thresholds->>'debater')::integer
    or (new_rank_thresholds->>'curator')::integer <= (new_rank_thresholds->>'connector')::integer
    or (new_rank_thresholds->>'legend')::integer <= (new_rank_thresholds->>'curator')::integer then
    raise exception 'Rank thresholds must be increasing';
  end if;
  update public.platform_settings set
    streak_days_displayed = displayed_days,
    streak_max_protections = max_protections,
    streak_renewal = renewal_period,
    rank_thresholds = new_rank_thresholds,
    updated_by = auth.uid(), updated_at = now()
  where singleton = true;
end;
$$;
revoke all on function public.owner_update_platform_settings(integer, integer, text, jsonb) from public, anon;
grant execute on function public.owner_update_platform_settings(integer, integer, text, jsonb) to authenticated;

