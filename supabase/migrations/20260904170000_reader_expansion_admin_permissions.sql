create or replace function public.prevent_self_admin_change()
returns trigger language plpgsql set search_path = public as $$
begin
  if auth.uid() is not null
    and current_setting('app.allow_role_change', true) is distinct from 'true'
    and (
      new.is_admin is distinct from old.is_admin
      or new.is_owner is distinct from old.is_owner
      or new.admin_permissions is distinct from old.admin_permissions
      or new.reader_rank is distinct from old.reader_rank
      or new.rank_manual is distinct from old.rank_manual
    ) then
    raise exception 'role, permission and rank changes require authorized functions';
  end if;
  return new;
end;
$$;

