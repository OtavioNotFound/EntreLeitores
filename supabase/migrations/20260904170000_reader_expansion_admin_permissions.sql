create or replace function public.limit_monthly_streak_protections()
returns trigger language plpgsql set search_path = public as $$
declare configured_limit integer;
begin
  select streak_max_protections into configured_limit from public.platform_settings where singleton = true;
  configured_limit := coalesce(configured_limit, 5);
  if exists (select 1 from public.reading_sessions where user_id = new.user_id and occurred_on = new.protected_on) then
    raise exception 'reading already registered on this day';
  end if;
  if (select count(*) from public.streak_protections where user_id = new.user_id
      and date_trunc('month', protected_on) = date_trunc('month', new.protected_on)) >= configured_limit then
    raise exception 'monthly protection limit reached';
  end if;
  return new;
end;
$$;

