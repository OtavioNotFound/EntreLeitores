create or replace function public.apply_automatic_streak_protections()
returns integer language plpgsql security definer set search_path = public as $$
declare last_activity date; target_day date; first_day date; configured_days integer; configured_limit integer; applied integer := 0;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  select streak_days_displayed, streak_max_protections into configured_days, configured_limit
  from public.platform_settings where singleton = true;
  configured_days := coalesce(configured_days, 30);
  configured_limit := coalesce(configured_limit, 5);
  select max(activity_day) into last_activity from (
    select max(occurred_on) activity_day from public.reading_sessions where user_id = auth.uid()
    union all
    select max(protected_on) from public.streak_protections where user_id = auth.uid() and protected_on < current_date
  ) activity;
  if last_activity is null then return 0; end if;
  first_day := greatest(last_activity + 1, current_date - configured_days);
  if first_day > current_date - 1 then return 0; end if;
  for target_day in select generate_series(first_day, current_date - 1, interval '1 day')::date loop
    if exists (select 1 from public.reading_sessions where user_id = auth.uid() and occurred_on = target_day) then continue; end if;
    if (select count(*) from public.streak_protections where user_id = auth.uid()
        and date_trunc('month', protected_on) = date_trunc('month', target_day)) >= configured_limit then continue; end if;
    insert into public.streak_protections(user_id, protected_on, status)
    values(auth.uid(), target_day, 'used') on conflict(user_id, protected_on) do nothing;
    if found then applied := applied + 1; end if;
  end loop;
  return applied;
end;
$$;
revoke all on function public.apply_automatic_streak_protections() from public, anon;
grant execute on function public.apply_automatic_streak_protections() to authenticated;
