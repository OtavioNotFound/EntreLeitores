create or replace function public.owner_set_admin_permissions(target_user_id uuid, grant_admin boolean, granted_permissions text[] default '{}')
returns void language plpgsql security definer set search_path = public as $$
declare allowed_permissions constant text[] := array[
  'books.view','books.create','books.edit','books.unpublish','books.delete','books.files',
  'readers.view','ranks.manage','achievements.grant','achievements.remove',
  'clubs.view','clubs.edit','clubs.delete',
  'reports.view','reports.resolve','reports.archive','streak.manage'
];
begin
  if not public.is_app_owner() then raise exception 'Owner access required'; end if;
  if not exists (select 1 from public.profiles where id = target_user_id) then raise exception 'User not found'; end if;
  if exists (select 1 from public.profiles where id = target_user_id and is_owner) then raise exception 'Owner roles cannot be changed here'; end if;
  if exists (select 1 from unnest(coalesce(granted_permissions, '{}')) permission where not permission = any(allowed_permissions)) then
    raise exception 'Invalid administrator permission';
  end if;
  perform set_config('app.allow_role_change', 'true', true);
  update public.profiles
  set is_admin = grant_admin,
      admin_permissions = case when grant_admin then coalesce(granted_permissions, '{}') else '{}' end
  where id = target_user_id;
end;
$$;
revoke all on function public.owner_set_admin_permissions(uuid, boolean, text[]) from public, anon;
grant execute on function public.owner_set_admin_permissions(uuid, boolean, text[]) to authenticated;

create or replace function public.owner_set_admin(target_user_id uuid, grant_admin boolean)
returns void language plpgsql security definer set search_path = public as $$
begin
